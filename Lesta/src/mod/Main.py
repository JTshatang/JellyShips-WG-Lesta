"""Register the fleet visual resources when the startup switch is enabled."""

API_VERSION = "API_v1.0"
SETTINGS_FILE = "settings.txt"


def enabled_at_startup() -> bool:
    loader = utils  # type: ignore[name-defined]
    settings_path = loader.getModDir() + "/" + SETTINGS_FILE
    if not loader.isFile(settings_path):
        loader.logInfo("[JellyShips04Coverage] Disabled: {} (settings file missing)".format(settings_path))
        return False

    try:
        with open(settings_path, "rb") as settings:
            raw = settings.read(129)
    except:  # API_v1.0 does not expose Python exception classes.
        loader.logInfo("[JellyShips04Coverage] Disabled: {} (cannot read settings)".format(settings_path))
        return False

    switch = raw.removeprefix(b"\xef\xbb\xbf").strip()
    if len(raw) > 128 or switch not in (b"enabled=true", b"enabled=false"):
        loader.logInfo(
            "[JellyShips04Coverage] Disabled: {} (expected enabled=true or enabled=false)".format(settings_path)
        )
        return False
    if switch == b"enabled=false":
        loader.logInfo("[JellyShips04Coverage] Disabled by {}".format(settings_path))
        return False
    return True


